// Publishes the built extension into the GrowDesk web app, so GrowDesk can offer it:
//   public/downloads/growdesk-capture.zip  - "Download GrowDesk Capture" (Load unpacked)
//   public/capture/growdesk-capture.crx    - signed package for policy force-install
//   lib/capture-extension.ts               - the version GrowDesk shows and puts in update.xml
//
// The extension lives in the GrowDesk repository (extension/), next to the web app (frontend/).
// Run after "npm run pack", or use "npm run publish:growdesk", which packs first.
//   node scripts/publish-growdesk.mjs            -> ../frontend
//   node scripts/publish-growdesk.mjs <folder>   -> another GrowDesk frontend
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync, copyFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createZip } from './zip.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DIST = resolve(ROOT, 'dist');
const { version } = JSON.parse(readFileSync(resolve(ROOT, 'package.json'), 'utf8'));
const CRX = resolve(ROOT, `crm-capture-${version}.crx`);

function fail(message) {
  console.error(`[publish] ${message}`);
  process.exit(1);
}

const FRONTEND = resolve(process.argv[2] ?? process.env.GROWDESK_FRONTEND ?? resolve(ROOT, '..', 'frontend'));
if (!existsSync(join(FRONTEND, 'package.json')) || !existsSync(join(FRONTEND, 'public'))) fail(`${FRONTEND} is not the GrowDesk frontend.`);
if (!existsSync(DIST)) fail('dist/ is missing - run "npm run pack" first.');
if (!existsSync(CRX)) fail(`${CRX} is missing - run "npm run pack" first.`);

const manifest = JSON.parse(readFileSync(join(DIST, 'manifest.json'), 'utf8'));
if (manifest.version !== version) fail(`dist/ is version ${manifest.version}, package.json says ${version}. Run "npm run pack".`);
if (!manifest.key) fail('manifest.json has no "key", so the extension ID would not be stable.');

/** The extension ID, derived from the manifest key the way Chrome does. */
const extensionId = [...createHash('sha256').update(Buffer.from(manifest.key, 'base64')).digest().subarray(0, 16)]
  .map((b) => b.toString(16).padStart(2, '0'))
  .join('')
  .replace(/[0-9a-f]/g, (c) => 'abcdefghijklmnop'[parseInt(c, 16)]);

if (manifest.update_url?.includes('localhost')) {
  console.warn(`[publish] Note: this package looks for updates at ${manifest.update_url}.`);
  console.warn('[publish] For PCs that get it from GrowDesk, build with GROWDESK_UPDATE_URL=https://<growdesk>/capture/update.xml');
}

// The download: dist/ inside a "growdesk-capture" folder, ready for Load unpacked.
function collect(dir, prefix) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory()
      ? collect(full, `${prefix}/${name}`)
      : [{ name: `${prefix}/${name}`, data: readFileSync(full) }];
  });
}
const { buffer } = createZip(collect(DIST, 'growdesk-capture'));

mkdirSync(join(FRONTEND, 'public', 'downloads'), { recursive: true });
mkdirSync(join(FRONTEND, 'public', 'capture'), { recursive: true });
writeFileSync(join(FRONTEND, 'public', 'downloads', 'growdesk-capture.zip'), buffer);
copyFileSync(CRX, join(FRONTEND, 'public', 'capture', 'growdesk-capture.crx'));
writeFileSync(
  join(FRONTEND, 'lib', 'capture-extension.ts'),
  `// Generated by extension/scripts/publish-growdesk.mjs - do not edit by hand.

/** The GrowDesk Capture Chrome extension GrowDesk currently offers. */
export const CAPTURE_EXTENSION = {
  id: "${extensionId}",
  version: "${version}",
  download: "/downloads/growdesk-capture.zip",
  crx: "/capture/growdesk-capture.crx",
  updateManifest: "/capture/update.xml",
  /** Where this build looks for updates (set at build time). */
  builtUpdateUrl: "${manifest.update_url ?? ''}",
} as const;
`,
);

for (const file of ['public/downloads/growdesk-capture.zip', 'public/capture/growdesk-capture.crx', 'lib/capture-extension.ts']) {
  console.log(`[publish] ${relative(process.cwd(), join(FRONTEND, file))}`);
}
console.log(`[publish] GrowDesk Capture ${version} is ready to deploy with GrowDesk.`);
